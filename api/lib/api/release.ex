defmodule Api.Release do
  @moduledoc """
  Compiled releases don't bundle Mix, so `mix ecto.migrate` doesn't exist at
  runtime in production - this is invoked instead via `bin/api eval
  "Api.Release.migrate()"`.
  """

  @app :api

  def migrate do
    load_app()

    for repo <- repos() do
      {:ok, _, _} = Ecto.Migrator.with_repo(repo, &Ecto.Migrator.run(&1, :up, all: true))
    end
  end

  def rollback(repo, version) do
    load_app()
    {:ok, _, _} = Ecto.Migrator.with_repo(repo, &Ecto.Migrator.run(&1, :down, to: version))
  end

  defp repos do
    Application.fetch_env!(@app, :ecto_repos)
  end

  defp load_app do
    Application.load(@app)
  end
end
